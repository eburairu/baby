
def format_dict(d, name):
    print(f"    {name}: {{")
    sorted_keys = sorted(d.keys())
    for i, k in enumerate(sorted_keys):
        vals = d[k]
        # vals is (p3, p50, p97)
        # Output: 0: { p3: 46.3, p50: 49.9, p97: 53.4 }
        line = f"      {k}: {{ p3: {vals[0]}, p50: {vals[1]}, p97: {vals[2]} }}"
        if i < len(sorted_keys) - 1:
            line += ","
        print(line)
    print("    },")

